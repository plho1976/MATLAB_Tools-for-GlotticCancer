function s=tableHTML(t)
s="<div class='scroll'><table><thead><tr>";
for name=string(t.Properties.VariableNames), s=s+"<th>"+escapeHTML(replace(name,'_',' '))+"</th>"; end
s=s+"</tr></thead><tbody>";
for i=1:height(t)
    s=s+"<tr>";
    for j=1:width(t)
        value=t{i,j}; if iscell(value), value=value{1}; end
        if isnumeric(value)
            if isnan(value), value="--";
            elseif contains(lower(t.Properties.VariableNames{j}),'p') && ...
                    (endsWith(t.Properties.VariableNames{j},'_P'))
                value=string(sprintf('%.4g',value));
            else, value=string(sprintf('%.4g',value)); end
        end
        s=s+"<td>"+escapeHTML(string(value))+"</td>";
    end
    s=s+"</tr>";
end
s=s+"</tbody></table></div>";
end

function s=escapeHTML(s)
s=replace(string(s),'&','&amp;'); s=replace(s,'<','&lt;'); s=replace(s,'>','&gt;');
s=replace(s,'"','&quot;'); s=replace(s,"'",'&#39;');
end
