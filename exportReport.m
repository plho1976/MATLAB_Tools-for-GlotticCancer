function files = exportReport(data, results, outdir, figureFiles)
%EXPORTREPORT Export numeric tables, manuscript tables and a browsable report.
arguments
    data (1,1) struct
    results (1,1) struct
    outdir (1,1) string
    figureFiles (:,1) string = strings(0,1)
end
tableDir=fullfile(outdir,'Tables'); if ~isfolder(tableDir), mkdir(tableDir); end
files=struct('report',fullfile(outdir,'Report.html'),'workbook',fullfile(outdir,'Analysis_Tables.xlsx'), ...
    'patient_csv',fullfile(outdir,'paired_plan_patient_data.csv'), ...
    'json',fullfile(outdir,'analysis_results.json'),'mat',fullfile(outdir,'analysis_results.mat'), ...
    'methods',fullfile(outdir,'Methods.txt'),'figures',figureFiles);
names=string(fieldnames(results.tables)); csvs=strings(numel(names),1);
for i=1:numel(names)
    t=results.tables.(names(i)); csvs(i)=fullfile(tableDir,names(i)+'.csv');
    writetable(t,csvs(i));
    writetable(t,files.workbook,'Sheet',names(i),'UseExcel',false,'WriteMode','overwritesheet');
end
writetable(data.patientTable,files.patient_csv);
writetable(data.patientTable,files.workbook,'Sheet','Patient_Data','UseExcel',false,'WriteMode','overwritesheet');
methods=[ ...
    "Analysis Data of glottic cancer"; ...
    "Source: "+string(results.analysis.source_file)+"; worksheet SO LIEU."; ...
    "Pairs: "+string(results.analysis.n_paired_patients)+". All patient IDs in outputs are anonymous."; ...
    "3DCRT/PBC and IMRT/AAA are paired whole planning workflows."; ...
    "Source label 3DCRT/PCB is interpreted as PBC, following the supplied planning report."; ...
    "Raw selected cells are validated and derived endpoints are recomputed on each import."; ...
    "Worse-side mean = max(left Dmean, right Dmean) in each plan; peak = max(left Dmax, right Dmax) independently."; ...
    "Arithmetic bilateral mean = (left Dmean + right Dmean)/2; no volume weighting."; ...
    "All deltas = IMRT minus 3DCRT. Scatterplot reduction = 3DCRT minus IMRT."; ...
    "V66 values in the current Excel layout are already percent; V66 differences are percentage points."; ...
    "Sample SD uses n-1. Quartiles use linear interpolation h=1+(n-1)*p, matching NumPy."; ...
    "Mean-difference 95% CI uses Student t with n-1 degrees of freedom; tests are two-sided."; ...
    "Wilcoxon uses exact random-sign probabilities on twice the midranks; differences rounded to 8 decimals only for ranking; zeros omitted."; ...
    "Binary proportions use exact Clopper-Pearson 95% CI. McNemar is the exact symmetric binomial test on discordant pairs."; ...
    "Holm adjustment: all 15 secondary continuous paired-t tests excluding worse-side Dmean; all 10 binary tests including composite checks."; ...
    "Primary paired-t p is unadjusted. All confidence intervals are nominal, unadjusted 95% intervals."; ...
    "Spearman uses midranks with the t approximation; Pearson intervals use Fisher z. Correlation p values are unadjusted."; ...
    "Carotid cutoffs: Dmean <20 Gy and peak Dmax <=50 Gy. Target checks: D95 >=66 Gy; D99.9 >=62.7 Gy; Dmax <=72.6 Gy."; ...
    "Table3 omits V66 and the mean-plus-target-only criterion from the 10-test family; full family is in TableS3."; ...
    "Patient relative reduction = 100*(3DCRT-IMRT)/3DCRT; zero baselines are undefined and excluded from this descriptor only."; ...
    "Bootstrap: "+string(results.bootstrap.n_resamples)+" paired resamples; seed "+string(results.bootstrap.seed)+"; MATLAB mt19937ar."; ...
    "MATLAB bootstrap draws differ from reference NumPy PCG64 draws; deterministic analytic results reproduce the reference."; ...
    "Empty conditional denominators and undefined correlations appear as NaN/null or --, with status in JSON."; ...
    "Exploratory analysis only: no clinical outcomes or injury thresholds are estimated."; ...
    string(results.data_concerns(:)); ...
    "MATLAB: "+string(results.analysis.matlab_version)+"; tool version: "+string(results.analysis.code_version)];
writeText(files.methods,strjoin(methods,newline));
results.outputFiles=files;
j=results;
for i=1:numel(names), j.tables.(names(i))=table2struct(results.tables.(names(i))); end
writeText(files.json,string(jsonencode(j,'PrettyPrint',true,'ConvertInfAndNaN',true)));
save(files.mat,'data','results');
writeText(files.report,htmlReport(results,methods,figureFiles));
files.table_csv=csvs;
allFiles=[files.report;files.workbook;files.patient_csv;files.json;files.mat;files.methods;csvs;figureFiles];
manifest=struct('completed',true,'code_version',results.analysis.code_version, ...
    'n_paired_patients',results.analysis.n_paired_patients,'files',allFiles);
writeText(fullfile(outdir,'Manifest.json'),string(jsonencode(manifest,'PrettyPrint',true)));
end

function writeText(path,value)
[fid,msg]=fopen(path,'w','n','UTF-8');
if fid<0, error('glottic:WriteFailed','Cannot write %s: %s',path,msg); end
guard=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',value);
end

